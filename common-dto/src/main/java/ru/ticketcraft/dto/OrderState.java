package ru.ticketcraft.dto;

/**
 * Жизненный цикл заказа билета в системе TicketCraft
 */
public enum OrderState {
	/** Заказ создан, места временно заблокированы (пессимистичная блокировка) */
	CREATED,

	/** Заказ успешно оплачен (места закрепляются за пользователем навсегда) */
	PAID,

	/** Ошибка оплаты или таймаут резерва (места освобождаются в каталоге) */
	CANCELED,

	/** Билет успешно отправлен клиенту */
	DELIVERED
}
